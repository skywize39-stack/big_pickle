    inline const Glyph* Find( char c )
    {
        if ( c >= 'a' && c <= 'z' ) c = (char)( c - 'a' + 'A' );
        for ( const Glyph& g : kGlyphs )
            if ( g.c == c ) return &g;
        for ( const Glyph& g : kGlyphs )
            if ( g.c == '?' ) return &g;
        return nullptr;
    }

    inline float TextWidth( const char* s )
    {
        int w = 0;
        for ( const char* p = s; *p; ++p )
        {
            const Glyph* g = Find( *p );
            if ( !g ) continue;
            w += (int)strlen( g->rows[ 0 ] ) + 1;
        }
        return (float)( w > 0 ? w - 1 : 0 );
    }

    // Draws `s` with its top-left at `pos` (snapped to whole pixels).
    inline void Draw( ImDrawList* dl, ImVec2 pos, ImU32 col, const char* s )
    {
        float x = std::floor( pos.x ), y = std::floor( pos.y );
        for ( const char* p = s; *p; ++p )
        {
            const Glyph* g = Find( *p );
            if ( !g ) continue;
            const int w = (int)strlen( g->rows[ 0 ] );
            for ( int r = 0; r < kHeight; ++r )
            {
                const char* row = g->rows[ r ];
                for ( int c = 0; c < w; )
                {
                    if ( row[ c ] != '#' ) { ++c; continue; }
                    int e = c;
                    while ( e < w && row[ e ] == '#' ) ++e;   // merge runs
                    dl->AddRectFilled( ImVec2( x + c, y + r ), ImVec2( x + e, y + r + 1 ), col );
                    c = e;
                }
            }
            x += w + 1;
        }
    }
